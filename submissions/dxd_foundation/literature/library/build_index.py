#!/usr/bin/env python3
"""Build INDEX.md (cards by facet, with verification status and read depth) and
../audit/CARD_FACET_CHECKS.md (every "Facet check:" line on a card). Stdlib only.
Run from anywhere: python3 literature/library/build_index.py [--check]"""
import pathlib
import re
import sys

HERE = pathlib.Path(__file__).resolve().parent
LIT = HERE.parent
NAMES = {
    "A": "The record", "B": "The dispute", "C": "Spacing to literacy", "D": "Reading science",
    "E": "Human-factors frame", "F": "Parallel moves", "G": "Nadella and his lineage",
    "H": "Candidate moves", "I": "Understanding through action", "J": "Who holds the convention",
    "K": "Training and cause", "X": "Counter-case", "Z": "Gap search",
}


def facets_of():
    out = {}
    for f in sorted((LIT / "facets").glob("*.bib")):
        for k in re.findall(r"^@\w+\s*\{\s*([^,\s]+)", f.read_text(), re.M):
            out.setdefault(k, []).append(f.name[0])
    return out


def build():
    fac = facets_of()
    groups, checks, tally = {}, [], {"confirmed": 0, "corrected": 0, "could not verify": 0, "unverified": 0}
    depth = {"full_text": 0, "partial": 0}
    for f in sorted(HERE.glob("*.md")):
        if f.name in ("README.md", "INDEX.md"):
            continue
        t = f.read_text()
        ref = re.sub(r"^#\s*", "", t.splitlines()[0]).strip()
        m = re.search(r"\*\*Verdict:\*\*\s*([a-z ]+)", t.split("## S2 adversarial verification")[-1]) \
            if "## S2 adversarial verification" in t else None
        verdict = m.group(1).strip() if m else "unverified"
        verdict = next((v for v in ("confirmed", "corrected", "could not verify") if verdict.startswith(v)), "unverified")
        tally[verdict] += 1
        d = re.search(r"\*\*Read depth:\*\*\s*([a-z_]+)", t)
        d = "full_text" if d and d.group(1) == "full_text" else "partial"
        depth[d] += 1
        letters = fac.get(f.stem, ["?"])
        mark = {"confirmed": "✓", "corrected": "✓*", "could not verify": "⚠", "unverified": "·"}[verdict]
        short = ref if len(ref) <= 170 else ref[:167].rsplit(" ", 1)[0] + "…"
        line = f"- {mark} [{short}]({f.name}) — {'full text' if d == 'full_text' else 'partial read'}; facets {', '.join(letters)}"
        groups.setdefault(letters[0], []).append(line)
        body = t.split("## S2 adversarial verification")[0]
        for c in re.findall(r"Facet check:\**\s*(.+?)(?:\n\n|\n- |\n##|\Z)", body, re.S):
            checks.append((letters[0], f.stem, " ".join(c.split())))
    n = sum(tally.values())
    idx = [
        "# Contextual bibliography — index", "",
        "*Generated by `build_index.py`; do not edit by hand. Agent-written cards; the author has not reviewed them.*", "",
        f"{n} cards, one per source read from full text on 2026-10-13, each re-checked against its source by a "
        f"second agent: {tally['confirmed']} confirmed, {tally['corrected']} corrected in place, "
        f"{tally['could not verify']} could not be verified. {depth['full_text']} rest on a full read and "
        f"{depth['partial']} on a partial read, which the card's Read depth line itemises.", "",
        "**Marks.** ✓ confirmed on re-check. ✓* corrected: the verifier found and fixed an error, recorded in the "
        "card's S2 section. ⚠ could not verify. A card is listed under the first facet that cites its source.", "",
        "Places where a full reading disagrees with a facet file are collected in "
        "[`../audit/CARD_FACET_CHECKS.md`](../audit/CARD_FACET_CHECKS.md).", "",
    ]
    for letter in sorted(groups, key=lambda x: (x == "?", x)):
        idx += [f"## Facet {letter} — {NAMES.get(letter, 'not in a facet bib')} ({len(groups[letter])})", ""] + groups[letter] + [""]
    chk = [
        "# Facet checks from the card library", "",
        "*Generated by `../library/build_index.py`. Each line is a card writer's note where the full text of a "
        "source says something other than a facet file says about it. Card writers wrote these before the S2 "
        "verification pass; where a card was later corrected, the card is the authority.*", "",
        f"{len(checks)} notes across {len({c[1] for c in checks})} cards.", "",
    ]
    last = None
    for letter, key, text in sorted(checks):
        if letter != last:
            chk += [f"## Facet {letter} — {NAMES.get(letter, '')}", ""]
            last = letter
        chk.append(f"- [`{key}`](../library/{key}.md): {text}")
    return "\n".join(idx).rstrip() + "\n", "\n".join(chk).rstrip() + "\n"


if __name__ == "__main__":
    idx, chk = build()
    targets = [(HERE / "INDEX.md", idx), (LIT / "audit" / "CARD_FACET_CHECKS.md", chk)]
    if "--check" in sys.argv:
        stale = [str(p) for p, s in targets if not p.exists() or p.read_text() != s]
        if stale:
            sys.exit("stale: " + ", ".join(stale))
        print("card index current")
    else:
        for p, s in targets:
            p.write_text(s)
        print("wrote", ", ".join(p.name for p, _ in targets))
