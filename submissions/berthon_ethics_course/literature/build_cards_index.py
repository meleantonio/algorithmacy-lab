#!/usr/bin/env python3
"""Generate literature/cards/REFERENCES.md from the arm's reference cards.

Adapted from org_frontier/research/build_cards_index.py for this arm's single card directory.
Deterministic: output depends only on the card files on disk (sorted).

    python3 literature/build_cards_index.py          # rewrite cards/REFERENCES.md
    python3 literature/build_cards_index.py --check  # exit 1 if REFERENCES.md is stale
"""
import collections
import glob
import os
import re
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
CARDS = os.path.join(HERE, "cards")


def frontmatter(path):
    """Parse the leading frontmatter of a card into a flat dict (scalars only)."""
    fm = {}
    with open(path, encoding="utf-8") as f:
        text = f.read()
    m = re.match(r"^---\n(.*?)\n---\n", text, re.S)
    if not m:
        return fm
    for line in m.group(1).splitlines():
        mm = re.match(r"([A-Za-z_]+):\s*(.*)$", line)
        if mm:
            fm[mm.group(1)] = mm.group(2).strip()
    return fm


def build():
    paths = sorted(p for p in glob.glob(os.path.join(CARDS, "*.md")) if not p.endswith("REFERENCES.md"))
    rows = [(os.path.basename(p)[:-3], frontmatter(p)) for p in paths]
    basis = collections.Counter(fm.get("source_basis", "?") for _, fm in rows)
    verified = collections.Counter(fm.get("verified", "?") for _, fm in rows)
    L = ["# Reference cards: index", "",
         "Generated by `literature/build_cards_index.py`; do not edit by hand.", "",
         f"{len(rows)} cards. Source basis: " + ", ".join(f"{k} {v}" for k, v in sorted(basis.items())) + ".",
         "Verified: " + ", ".join(f"{k} {v}" for k, v in sorted(verified.items())) + ".", "",
         "| card | authors | year | title | basis | verified |", "| --- | --- | --- | --- | --- | --- |"]
    for key, fm in rows:
        title = fm.get("title", "").replace("|", "/")
        authors = fm.get("authors", "").replace("|", "/")
        L.append(f"| [{key}]({key}.md) | {authors} | {fm.get('year', '')} | {title} | "
                 f"{fm.get('source_basis', '')} | {fm.get('verified', '')} |")
    return "\n".join(L) + "\n"


if __name__ == "__main__":
    out = build()
    target = os.path.join(CARDS, "REFERENCES.md")
    if "--check" in sys.argv:
        ok = os.path.exists(target) and open(target, encoding="utf-8").read() == out
        print("REFERENCES.md is current" if ok else "REFERENCES.md is STALE: rerun literature/build_cards_index.py")
        sys.exit(0 if ok else 1)
    with open(target, "w", encoding="utf-8") as f:
        f.write(out)
    print(f"wrote {target}")
